/// Current time as whole seconds since the Unix epoch. Used for created/updated
/// timestamps stored as INTEGER columns.
pub fn now_unix() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0)
}
